import requests

def generate_response(prompt, mode="Demo", model="llama3.2"):
    prompt = (prompt or "").strip()

    if not prompt:
        return None, None, "Please enter a prompt."

    if "ollama" in str(mode).lower():
        try:
            response = requests.post(
                "http://localhost:11434/api/generate",
                json={
                    "model": model,
                    "prompt": prompt,
                    "stream": False
                },
                timeout=120
            )

            response.raise_for_status()
            data = response.json()
            answer = data.get("response", "").strip()

            if not answer:
                return None, None, "The local model returned an empty response."

            return answer, f"Ollama local model: {model}", None

        except requests.exceptions.ConnectionError:
            return None, None, (
                "Cannot connect to Ollama. Check that Ollama is running "
                "and that the selected model is installed."
            )
        except requests.exceptions.Timeout:
            return None, None, "The model took too long to respond."
        except requests.exceptions.RequestException as exc:
            return None, None, f"Ollama request failed: {exc}"
        except (ValueError, KeyError):
            return None, None, "Could not read the model response."

    answer = f"""
DEMO MODE — TEMPLATE RESPONSE

Your prompt has been received.

Prompt overview:
{prompt[:1200]}

Suggested response structure:

1. Objective
   Identify the main objective in the supplied prompt.

2. Key considerations
   Address the context, requirements and constraints.

3. Proposed response
   Develop a response that directly addresses the task.

4. Final review
   Check relevance, clarity, completeness and requested format.

Note: This is a demonstration template, not a response generated by an AI model.
Connect Ollama and select an installed model to generate a real model response.
""".strip()

    return answer, "PromptWise AI demonstration mode (template-based)", None
